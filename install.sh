#!/bin/sh
# codegraph-helper 安装脚本：
#   1) 拷贝服务脚本与 hooks 到 ~/.codegraph-helper/
#   2) 设置 git 全局 core.hooksPath 指向我们的 hooks
#   3) 注册 launchd 常驻服务（登录自启、异常自动拉起）
set -e

INSTALL_DIR="${CODEGRAPH_HELPER_HOME:-$HOME/.codegraph-helper}"
SCRIPT_DIR=$(cd "$(dirname "$0")" && pwd)
CONFIG="$INSTALL_DIR/config.json"
PLIST="$HOME/Library/LaunchAgents/com.codegraph.helper.plist"
LOG_DIR="$HOME/Library/Logs"
PORT="${CODEGRAPH_HELPER_PORT:-9377}"

# ---------- 依赖检查 ----------
for bin in curl git; do
  if ! command -v "$bin" >/dev/null 2>&1; then
    echo "ERROR: 未找到命令 $bin，无法继续"
    exit 1
  fi
done
PYTHON_BIN=$(command -v python3 || command -v python)
if [ -z "$PYTHON_BIN" ]; then
  echo "ERROR: 未找到 python3（可执行 xcode-select --install 安装命令行工具）"
  exit 1
fi

# ---------- 拷贝文件 ----------
echo "==> 安装目录: $INSTALL_DIR"
mkdir -p "$INSTALL_DIR/hooks"
cp "$SCRIPT_DIR/server.py" "$INSTALL_DIR/server.py"
for hook in pre-commit commit-msg pre-push prepare-commit-msg; do
  cp "$SCRIPT_DIR/hooks/$hook" "$INSTALL_DIR/hooks/$hook"
done
chmod +x "$INSTALL_DIR/server.py" \
  "$INSTALL_DIR/hooks/pre-commit" "$INSTALL_DIR/hooks/commit-msg" \
  "$INSTALL_DIR/hooks/pre-push" "$INSTALL_DIR/hooks/prepare-commit-msg"

# ---------- 命令入口（按优先级放到 PATH 里第一个可写的目录） ----------
CLI_LINK=""
for dir in /opt/homebrew/bin /usr/local/bin "$HOME/.npm-global/bin"; do
  if [ -d "$dir" ] && [ -w "$dir" ]; then
    CLI_LINK="$dir/codegraph-helper"
    break
  fi
done
if [ -n "$CLI_LINK" ]; then
  ln -sf "$INSTALL_DIR/server.py" "$CLI_LINK"
  echo "==> 已创建命令入口: $CLI_LINK（roots list/add/remove 管理生效目录）"
else
  echo "WARN: PATH 中没有可写的目录，可手动执行: sudo ln -sf $INSTALL_DIR/server.py /usr/local/bin/codegraph-helper"
  echo "      或直接用: python3 $INSTALL_DIR/server.py roots list"
fi

# ---------- 生成配置（已存在则保留） ----------
if [ -f "$CONFIG" ]; then
  echo "==> 保留已有配置: $CONFIG"
else
  CODEGRAPH_BIN=$(command -v codegraph || true)
  if [ -n "$CODEGRAPH_BIN" ]; then
    echo "==> 检测到 codegraph: $CODEGRAPH_BIN"
  else
    CODEGRAPH_BIN="codegraph"
    echo "WARN: PATH 中未找到 codegraph 命令，之后请手动修改 $CONFIG 中的 codegraph_bin"
  fi
  TOKEN=$(openssl rand -hex 16 2>/dev/null || LC_ALL=C tr -dc 'A-Za-z0-9' </dev/urandom | head -c 32)
  cat > "$CONFIG" <<EOF
{
  "port": $PORT,
  "token": "$TOKEN",
  "codegraph_bin": "$CODEGRAPH_BIN",
  "require_codegraph_index": true,
  "auto_init": true,
  "repo_roots": [],
  "exclude_roots": [],
  "sync_timeout_seconds": 600,
  "init_timeout_seconds": 1800
}
EOF
  chmod 600 "$CONFIG"
  echo "==> 已生成配置: $CONFIG"
fi

# ---------- token 文件（供 hook 读取） ----------
TOKEN_VALUE=$("$PYTHON_BIN" - "$CONFIG" <<'PYEOF'
import json, sys
print(json.load(open(sys.argv[1])).get("token", ""), end="")
PYEOF
)
printf '%s' "$TOKEN_VALUE" > "$INSTALL_DIR/token"
chmod 600 "$INSTALL_DIR/token"

# ---------- 生成通知类 hooks（写入实际端口与 token 路径） ----------
# post-commit / post-checkout / post-merge 分别覆盖 commit、切分支/checkout、pull/merge 三类变更
for hook_name in post-commit post-checkout post-merge; do
  cat > "$INSTALL_DIR/hooks/$hook_name" <<EOF
#!/bin/sh
# Generated by codegraph-helper install.sh ($hook_name)
# 1) 后台通知本地 sync 服务（3 秒超时，绝不阻塞 git 操作）
# 2) 转调仓库本地同名 hook（core.hooksPath 会屏蔽本地 hooks，这里还原行为）

URL="\${CODEGRAPH_HELPER_URL:-http://127.0.0.1:$PORT}"
TOKEN="\${CODEGRAPH_HELPER_TOKEN:-\$(cat "$INSTALL_DIR/token" 2>/dev/null)}"

if repo_root=\$(git rev-parse --show-toplevel 2>/dev/null); then
  curl -s -m 3 -G -X POST "\$URL/hook" \\
    -H "X-Codegraph-Token: \$TOKEN" \\
    --data-urlencode "repo=\$repo_root" \\
    --data-urlencode "source=\$(basename "\$0")" >/dev/null 2>&1 &
fi

HOOK_NAME=\$(basename "\$0")
GIT_DIR=\$(git rev-parse --git-dir 2>/dev/null)
if [ -n "\$GIT_DIR" ] && [ -x "\$GIT_DIR/hooks/\$HOOK_NAME" ] && [ "\$GIT_DIR/hooks/\$HOOK_NAME" != "\$0" ]; then
  "\$GIT_DIR/hooks/\$HOOK_NAME" "\$@" &
fi
exit 0
EOF
  chmod +x "$INSTALL_DIR/hooks/$hook_name"
done

# ---------- 生成 post-rewrite（rebase / amend 走这里，stdin 需要转发） ----------
cat > "$INSTALL_DIR/hooks/post-rewrite" <<EOF
#!/bin/sh
# Generated by codegraph-helper install.sh (post-rewrite)
# git rebase 和 commit --amend 会触发这个 hook（post-commit 不会）。
# stdin 是重写映射表，转调仓库本地同名 hook 时要原样喂回去。

URL="\${CODEGRAPH_HELPER_URL:-http://127.0.0.1:$PORT}"
TOKEN="\${CODEGRAPH_HELPER_TOKEN:-\$(cat "$INSTALL_DIR/token" 2>/dev/null)}"

STDIN_TMP=\$(mktemp -t codegraph-rewrite) || exit 0
cat > "\$STDIN_TMP"

if repo_root=\$(git rev-parse --show-toplevel 2>/dev/null); then
  curl -s -m 3 -G -X POST "\$URL/hook" \\
    -H "X-Codegraph-Token: \$TOKEN" \\
    --data-urlencode "repo=\$repo_root" \\
    --data-urlencode "source=\$(basename "\$0")" >/dev/null 2>&1 &
fi

HOOK_NAME=\$(basename "\$0")
GIT_DIR=\$(git rev-parse --git-dir 2>/dev/null)
if [ -n "\$GIT_DIR" ] && [ -x "\$GIT_DIR/hooks/\$HOOK_NAME" ] && [ "\$GIT_DIR/hooks/\$HOOK_NAME" != "\$0" ]; then
  "\$GIT_DIR/hooks/\$HOOK_NAME" "\$@" < "\$STDIN_TMP"
fi

rm -f "\$STDIN_TMP"
exit 0
EOF
chmod +x "$INSTALL_DIR/hooks/post-rewrite"

# ---------- 设置 git 全局 hooksPath ----------
echo "==> 设置 git 全局 core.hooksPath = $INSTALL_DIR/hooks"
git config --global core.hooksPath "$INSTALL_DIR/hooks"

# ---------- 注册 launchd 服务 ----------
cat > "$PLIST" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key>
  <string>com.codegraph.helper</string>
  <key>ProgramArguments</key>
  <array>
    <string>$PYTHON_BIN</string>
    <string>$INSTALL_DIR/server.py</string>
  </array>
  <key>RunAtLoad</key>
  <true/>
  <key>KeepAlive</key>
  <true/>
  <key>ThrottleInterval</key>
  <integer>10</integer>
  <key>EnvironmentVariables</key>
  <dict>
    <key>PATH</key>
    <string>/usr/local/bin:/opt/homebrew/bin:/usr/bin:/bin:/usr/sbin:/sbin</string>
  </dict>
  <key>StandardOutPath</key>
  <string>$LOG_DIR/codegraph-helper.log</string>
  <key>StandardErrorPath</key>
  <string>$LOG_DIR/codegraph-helper.err.log</string>
</dict>
</plist>
EOF
echo "==> 注册 launchd 服务: $PLIST"
launchctl bootout "gui/$(id -u)/com.codegraph.helper" 2>/dev/null || launchctl unload "$PLIST" 2>/dev/null || true
if launchctl bootstrap "gui/$(id -u)" "$PLIST" 2>/dev/null; then
  :
elif launchctl load "$PLIST" 2>/dev/null; then
  :
else
  echo "ERROR: launchctl 注册失败，请手动执行: launchctl load $PLIST"
  exit 1
fi

# ---------- 健康检查 ----------
sleep 1
if curl -s -m 3 "http://127.0.0.1:$PORT/health" >/dev/null 2>&1; then
  echo "==> 服务已启动: http://127.0.0.1:$PORT/health"
else
  echo "WARN: 服务暂未响应，请查看日志: $LOG_DIR/codegraph-helper.err.log"
fi

echo ""
echo "安装完成。commit / 切分支 / pull / rebase 之后，服务会自动同步 repo_roots 内已有 .codegraph/ 的仓库。"
echo "运行日志: $LOG_DIR/codegraph-helper.log"
echo "卸载方式: $SCRIPT_DIR/uninstall.sh"
